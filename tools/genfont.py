#!/usr/bin/env python3
"""Generate a C header with 8x16 ASCII glyphs from a Terminus BDF file.

Source: third_party/terminus/ter-u16n.bdf (Terminus Font, SIL OFL 1.1, ADR-004).
Output: third_party/terminus/terminus_font.h (data file, registered in quota).

Usage: python3 tools/genfont.py <in.bdf> <out.h>
"""
import sys

CELL_W, CELL_H = 8, 16


def parse_bdf(path):
    glyphs = {}
    bb_global = None
    cur = None
    rows = []
    with open(path, "r", encoding="latin-1") as f:
        for line in f:
            line = line.strip()
            if line.startswith("FONTBOUNDINGBOX"):
                _, w, h, ox, oy = line.split()
                bb_global = (int(w), int(h), int(ox), int(oy))
            elif line.startswith("STARTCHAR"):
                cur, rows = None, []
            elif line.startswith("ENCODING"):
                cur = int(line.split()[1])
            elif line.startswith("BBX"):
                _, w, h, ox, oy = line.split()
                cur_bb = (int(w), int(h), int(ox), int(oy))
                glyph_bb = cur_bb
            elif line.startswith("BITMAP"):
                pass
            elif line.startswith("ENDCHAR"):
                if cur is not None and 0x20 <= cur <= 0x7E:
                    glyphs[cur] = (glyph_bb, rows)
                cur = None
            elif line.startswith("ENDFONT"):
                break
            elif cur is not None and all(c in "0123456789ABCDEFabcdef" for c in line) and line:
                rows.append(int(line, 16))
    return bb_global, glyphs


def render(bb_global, glyphs):
    _, cell_h, fo_x, fo_y = bb_global  # fo_y: cell bottom relative to baseline (negative)
    cell_h = CELL_H
    # baseline row index within the cell (counting from the top)
    baseline_row = cell_h - 1 + fo_y  # fo_y negative -> rows of descent below baseline
    out = []
    for ch in range(0x20, 0x7F):
        cell = [0] * cell_h
        if ch in glyphs:
            (gw, gh, gx, gy), rows = glyphs[ch]
            for i, row in enumerate(rows):
                # glyph row i is at baseline-relative y = gy + gh - 1 - i (rows above baseline)
                y = baseline_row - (gy + gh - 1 - i)
                if 0 <= y < cell_h:
                    cell[y] = row & 0xFF  # 8px wide cell; mask to one byte
        out.append(cell)
    return out


def main():
    src, dst = sys.argv[1], sys.argv[2]
    bb_global, glyphs = parse_bdf(src)
    n = sum(1 for c in glyphs if 0x20 <= c <= 0x7E)
    sys.stderr.write(f"parsed {n} printable glyphs; FONTBOUNDINGBOX={bb_global}\n")
    cells = render(bb_global, glyphs)

    with open(dst, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/genfont.py from Terminus Font ter-u16n.bdf.\n")
        f.write(" * Terminus Font: SIL Open Font License 1.1 (see OFL.TXT). ADR-004.\n")
        f.write(" * DO NOT EDIT - regenerate with: make font\n")
        f.write(" */\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("#define FONT_W 8\n#define FONT_H 16\n#define FONT_FIRST 0x20\n#define FONT_LAST 0x7e\n\n")
        f.write("static const uint8_t font_glyphs[%d * %d] = {\n" % (0x7F - 0x20, CELL_H))
        for cell in cells:
            f.write("    " + ", ".join("0x%02x" % b for b in cell) + ",\n")
        f.write("};\n")
    sys.stderr.write(f"wrote {dst}\n")


if __name__ == "__main__":
    main()
